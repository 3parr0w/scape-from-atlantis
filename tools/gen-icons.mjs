// Regenerates src/icons-data.ts from the Iconify icon packs (only needed when you change the icon list).
//   npm i --no-save @iconify-json/fluent-emoji-flat @iconify-json/game-icons
//   node tools/gen-icons.mjs
// Licences: Fluent Emoji Flat = MIT (Microsoft). Game-icons.net = CC BY 3.0 (see README "Credits").
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
const require = createRequire(import.meta.url);
const fe = require("@iconify-json/fluent-emoji-flat/icons.json");
const gi = require("@iconify-json/game-icons/icons.json");
const FE = ["shark", "whale", "dolphin", "sailboat", "volcano", "shield", "desert-island"];
const GI = ["sea-serpent"];
const pick = (set, names) =>
  Object.fromEntries(
    names.map((n) => {
      if (!set.icons[n]) throw new Error("icon not found: " + n);
      return [n, set.icons[n].body.replace(/\s+fill="currentColor"/g, "")];
    }),
  );
const out =
  `// GENERATED by tools/gen-icons.mjs - do not edit by hand.\n` +
  `// fe: Fluent Emoji Flat (c) Microsoft, MIT licence, 32x32 grid.\n` +
  `// gi: game-icons.net (c) their authors, CC BY 3.0, 512x512 grid, single-colour (we paint them).\n` +
  `export const fe: Record<string, string> = ${JSON.stringify(pick(fe, FE), null, 1)};\n` +
  `export const gi: Record<string, string> = ${JSON.stringify(pick(gi, GI), null, 1)};\n`;
writeFileSync(new URL("../src/icons-data.ts", import.meta.url), out);
console.log("wrote src/icons-data.ts", out.length, "bytes");
